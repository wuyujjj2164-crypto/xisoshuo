    def __init__(self):
        # 人名说话模式：
        # 1. 限制2-3字人名（中文人名几乎全是2-3字）
        # 2. 要求前面不是汉字（防止从句子中间开始匹配）
        # 3. 人名和说话动词之间允许0-3个副词修饰字（如"李明不解地问"）
        # 说话动词位置模式（只匹配动词本身，不连带人名）
        # 后缀支持冒号、引号、空格、逗号、句号、问号、感叹号、分号（全角+半角）
        self._speech_verbs = re.compile(
            r'说道[：:,，。！？；;""""\s]*|'
            r'说[：:,，。！？；;""""\s]+|'
            r'问道[；。！？\s]|'
            r'问道[：:,，。！？；;""""\s]*|'
            r'问[。！？；:,，""""\s]|'
            r'答道[：:,，。！？；;""""\s]*|'
            r'回答[：:,，。！？；;""""\s]*|'
            r'喊道[：:,，。！？；;""""\s]*|'
            r'叫道[：:,，。！？；;""""\s]*|'
            r'大喊[：:,，。！？；;""""\s]*|'
            r'高呼[：:,，。！？；;""""\s]*|'
            r'喃喃[：:,，。！？；;""""\s]*|'
            r'低语[：:,，。！？；;""""\s]*|'
            r'嘟囔[：:,，。！？；;""""\s]*|'
            r'嘀咕[：:,，。！？；;""""\s]*|'
            r'轻声[：:,，。！？；;""""\s]*'
        )
        self._speaker_after = re.compile(
            r'(?:说道|说|问|答道|回答|喊道|叫道|喃喃|低语|嘟囔|嘀咕)[：:\s]*"'
        )
        self._location_indicators = [
            "在", "来到", "走进", "走出", "站在", "坐在", "回到",
            "离开", "前往", "抵达", "到达",
        ]
        self._time_indicators = [
            "清晨", "早晨", "上午", "中午", "下午", "傍晚", "黄昏",
            "晚上", "夜晚", "深夜", "黎明", "半夜", "午夜",
            "第二天", "次日", "几天后", "数日后",
        ]

    def analyze(self, novel: Novel) -> dict:
        """
        全面分析小说

        Args:
            novel: Novel 对象

        Returns:
            分析结果字典，包含角色、场景、对话等信息
        """
        all_text = "\n\n".join(ch.content for ch in novel.chapters)

        return {
            "characters": self._extract_characters(novel),
            "locations": self._extract_locations(all_text),
            "timeline": self._extract_timeline(all_text),
            "dialogue_samples": self._extract_dialogue_samples(novel),
            "chapter_summaries": self._summarize_chapters(novel),
        }

    def _extract_characters(self, novel: Novel) -> list[Character]:
        """
        提取角色信息

        基于对话动词识别人名，统计出场频率。
        采用"引号上下文"策略：只在引号前后 40 字范围内查找说话人，
        大幅降低误识别率。过滤常见非人名词，只保留出现 >=2 次的候选。
        """
        name_counts: dict[str, int] = {}
        name_contexts: dict[str, list[str]] = {}

        # 匹配弯引号和直引号对话
        dialogue_pattern = re.compile(r'[""""""]([^""""""]{1,400})[""""""]')

        for chapter in novel.chapters:
            content = chapter.content

            # 1) 在引号对话前后搜索说话人（更精确）
            for match in dialogue_pattern.finditer(content):
                start = match.start()
                end = match.end()

                # 对话前 50 字内回溯找说话人
                before = content[max(0, start - 50):start]
                for name in self._find_speaker_before_verb(before):
                    name_counts[name] = name_counts.get(name, 0) + 1
                    idx = before.rfind(name)
                    ctx = before[max(0, idx - 20):idx + 20]
                    name_contexts.setdefault(name, []).append(ctx)

                # 对话后 50 字内回溯找说话人
                after = content[end:min(len(content), end + 50)]
                for name in self._find_speaker_before_verb(after):
                    name_counts[name] = name_counts.get(name, 0) + 1
                    idx = after.find(name)
                    ctx = after[max(0, idx - 20):idx + 20]
                    name_contexts.setdefault(name, []).append(ctx)

            # 2) 全文扫描：找到所有说话动词，然后往前回溯2-6字找可能的人名
            for m in self._speech_verbs.finditer(content):
                # 从动词位置往前最多6个字，尝试2-3字人名
                verb_start = m.start()
                window_start = max(0, verb_start - 6)
                window = content[window_start:verb_start]

                # 尝试从后往前找2-3字的人名
                for length in (3, 2):
                    if len(window) >= length:
                        name = window[-length:]
                        # 名字必须只包含2-3个汉字
                        if not self._is_pure_chinese_name(name):
                            continue
                        # 人名前面不是汉字（或已到文本开头）
                        before_char_idx = window_start + len(window) - length - 1
                        if before_char_idx < 0 or not self._is_chinese(content[before_char_idx]):
                            if self._is_valid_name(name):
                                name_counts[name] = name_counts.get(name, 0) + 1
                                ctx_start = max(0, verb_start - 40)
                                ctx_end = min(len(content), verb_start + 20)
                                ctx = content[ctx_start:ctx_end].replace("\n", " ")
                                name_contexts.setdefault(name, []).append(ctx)
                                break  # 优先取较长的

        # 过滤：基于文本长度动态调整最小出现次数
        # 短文本（<3000字）保留1次，中等文本保留1次，超长文本可提高到2次
        total_len = sum(len(ch.content) for ch in novel.chapters)
        min_count = 1 if total_len < 10000 else 2
        name_counts = {n: c for n, c in name_counts.items() if c >= min_count}

        if not name_counts:
            # 如果没有找到任何角色，尝试放宽条件（出现1次也保留）
            for chapter in novel.chapters:
                for name in self._find_speaker_before_verb(chapter.content):
                    name_counts[name] = name_counts.get(name, 0) + 1

        # 按出场频率排序
        sorted_names = sorted(name_counts.items(), key=lambda x: x[1], reverse=True)

        characters = []
        for i, (name, count) in enumerate(sorted_names[:30], 1):  # 最多30个角色
            # 确定重要性
            total_mentions = sum(name_counts.values())
            ratio = count / total_mentions if total_mentions > 0 else 0

            if ratio > 0.15:
                importance = CharacterImportance.MAIN
            elif ratio > 0.03:
                importance = CharacterImportance.SUPPORTING
            else:
                importance = CharacterImportance.MINOR

            # 提取描述（从上下文中找形容词）
            description = self._extract_description(name_contexts.get(name, []))

            characters.append(
                Character(
                    id=f"char_{i:03d}",
                    name=name,
                    description=description,
                    importance=importance,
                )
            )

        return characters

    @staticmethod
    def _is_chinese(char: str) -> bool:
        """判断字符是否为汉字"""
        return '一' <= char <= '鿿'

    def _is_pure_chinese_name(self, name: str) -> bool:
        """检查是否为纯汉字（2-3字，无标点/数字/英文）"""
        return 2 <= len(name) <= 3 and all(self._is_chinese(c) for c in name)

    def _find_speaker_before_verb(self, text: str) -> list[str]:
        """
        在文本中从说话动词位置往前回溯找2-3字人名。
        返回所有有效的人名列表（去重）。
        """
        names = []
        for m in self._speech_verbs.finditer(text):
            verb_start = m.start()
            window_start = max(0, verb_start - 6)
            window = text[window_start:verb_start]
            for length in (3, 2):
                if len(window) >= length:
                    name = window[-length:]
                    # 名字必须只包含2-3个汉字（无标点/空格/数字）
                    if not self._is_pure_chinese_name(name):
                        continue
                    before_char_idx = window_start + len(window) - length - 1
                    if before_char_idx < 0 or not self._is_chinese(text[before_char_idx]):
                        if self._is_valid_name(name):
                            names.append(name)
                            break
        return names

    def _is_valid_name(self, name: str) -> bool:
        """验证是否为有效人名（排除常见误识别）"""
        if len(name) < 2:
            return False
        # 排除大量常见非人名词
        return name not in self._INVALID_NAMES

    def _extract_description(self, contexts: list[str]) -> str:
        """从上下文中提取角色描述"""
        if not contexts:
            return ""

        # 简单策略：取第一个包含该角色且长度合适的上下文
        for ctx in contexts[:3]:
            if 20 < len(ctx) < 100:
                return ctx.strip()

        return contexts[0][:100].strip() if contexts else ""

